// Keep only the runtime dependency closure of the packages the UI and artifact servers import.
// Usage: node prune_node_modules.mjs <project-root> <package>...
import { existsSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { basename, dirname, join } from "node:path";

const [root, ...entryPackages] = process.argv.slice(2);
if (!root || entryPackages.length === 0)
  throw new Error("Usage: prune_node_modules.mjs <project-root> <package>...");

const keep = new Set();

function locate(name, from) {
  for (let dir = from; ; ) {
    const candidate = join(dir, "node_modules", name);
    if (existsSync(join(candidate, "package.json"))) return candidate;
    let parent = dirname(dir);
    if (basename(parent) === "node_modules") parent = dirname(parent);
    if (parent === dir) return null;
    dir = parent;
  }
}

function visit(packageDir) {
  if (keep.has(packageDir)) return;
  keep.add(packageDir);
  const manifest = JSON.parse(
    readFileSync(join(packageDir, "package.json"), "utf8"),
  );
  for (const dependency of Object.keys({
    ...manifest.dependencies,
    ...manifest.optionalDependencies,
  })) {
    const found = locate(dependency, packageDir);
    if (found) visit(found);
  }
}

for (const name of entryPackages) {
  const found = locate(name, root);
  if (!found) throw new Error(`Required package is not installed: ${name}`);
  visit(found);
}

function prune(modulesDir) {
  for (const name of readdirSync(modulesDir)) {
    const path = join(modulesDir, name);
    if (name.startsWith("@")) {
      prune(path);
      continue;
    }
    if (!keep.has(path)) {
      rmSync(path, { recursive: true, force: true });
      continue;
    }
    const nested = join(path, "node_modules");
    if (existsSync(nested)) prune(nested);
  }
}

prune(join(root, "node_modules"));
rmSync(join(root, "node_modules", ".bin"), { recursive: true, force: true });
console.log(`Kept ${keep.size} runtime packages`);
